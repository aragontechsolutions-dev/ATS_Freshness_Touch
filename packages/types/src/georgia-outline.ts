/**
 * A cuantas millas esta el punto de Georgia MAS LEJANO de un origen dado.
 *
 * Sirve para una sola decision, y es la que hace honesto el mapa: **si el
 * radio de una zona llega mas lejos que esto, esa zona cubre el estado
 * entero**, y entonces su forma real es el contorno y no un circulo.
 *
 * Se calcula y no se escribe a mano porque la base de operaciones es
 * configurable: el dia que la empresa se mude, la respuesta cambia sola en
 * vez de quedarse una constante mintiendo.
 *
 * Son 476 puntos y una raiz cuadrada por punto: se ejecuta una vez al
 * montar el mapa, no por fotograma.
 */
export function farthestGeorgiaMiles(lat: number, lon: number): number {
  let lejos = 0;
  for (const [puntoLat, puntoLon] of GEORGIA_OUTLINE) {
    const millas = haversineMiles(lat, lon, puntoLat, puntoLon);
    if (millas > lejos) lejos = millas;
  }
  return lejos;
}

